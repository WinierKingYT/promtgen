import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import process from 'node:process';
import {
  runPlannerBenchmark,
  type PlannerBenchmarkReport,
  type PlannerBenchmarkScenario
} from '../src/v4/benchmarks/planner-benchmark.js';

const checkOnly = process.argv.includes('--check');
const scenarioPath = path.resolve('benchmarks', 'planner', 'scenarios.json');
const reportPath = path.resolve('benchmarks', 'planner', 'latest-report.json');
const markdownPath = path.resolve('docs', 'product', 'BENCHMARK_REPORT.md');
const modulePath = path.resolve('src', 'v4', 'product', 'generated-benchmark-evidence.ts');
const scenarios = JSON.parse(await readFile(scenarioPath, 'utf8')) as PlannerBenchmarkScenario[];

let generatedAt = new Date().toISOString();
if (checkOnly) {
  try {
    const current = JSON.parse(await readFile(reportPath, 'utf8')) as PlannerBenchmarkReport;
    generatedAt = current.generatedAt;
  } catch {
    generatedAt = 'missing-report';
  }
}

const report = runPlannerBenchmark(scenarios, generatedAt);
const json = `${JSON.stringify(report, null, 2)}\n`;
const moduleSource = `// Generated by \`npm run benchmark:planner\`; do not edit manually.
export const PLANNER_BENCHMARK_EVIDENCE: {
  suiteId: string;
  reportPath: string;
  generatedAt: string;
  capabilities: Record<string, { completed: number; passed: number }>;
} = Object.freeze(${JSON.stringify({
  suiteId: report.suiteId,
  reportPath: 'benchmarks/planner/latest-report.json',
  generatedAt: report.generatedAt,
  capabilities: report.capabilities
}, null, 2)});
`;
const resultRows = report.results.map(result =>
  `| ${result.title} | ${result.domain} | ${result.passed ? 'Geçti' : 'Kaldı'} | ${result.metrics.readiness} | ${Math.round(result.metrics.mustTaskCoverage * 100)}% | ${Math.round(result.metrics.mustTestCoverage * 100)}% | ${result.metrics.exportFiles} |`
).join('\n');
const markdown = `# Planner Çekirdek Benchmark Raporu

Bu rapor \`benchmarks/planner/scenarios.json\` senaryolarının gerçek canonical model, task compiler, readiness ve exporter üretim zincirinde çalıştırılmasıyla üretilir.

- Suite: \`${report.suiteId}\`
- Son çalışma: ${report.generatedAt}
- Sonuç: ${report.passedCount}/${report.scenarioCount}
- Başarı oranı: %${Math.round(report.passRate * 100)}
- Kapsam: deterministic ürün sözleşmesi benchmark'ı; gerçek kullanıcı sonucu değildir.

| Senaryo | Alan | Sonuç | Readiness | Must→Görev | Must→Test | Export dosyası |
|---|---|---|---:|---:|---:|---:|
${resultRows}

## Capability kanıtı

${Object.entries(report.capabilities).map(([id, evidence]) => `- **${id}:** ${evidence.passed}/${evidence.completed}`).join('\n')}

Bu rapor kullanıcı kanıtı yerine geçmez. Capability ancak ayrı kullanıcı araştırması eşiği de karşılandığında Stable olabilir.
`;

const outputs = [
  [reportPath, json],
  [modulePath, moduleSource],
  [markdownPath, markdown]
] as const;

if (checkOnly) {
  const mismatches: string[] = [];
  for (const [filePath, expected] of outputs) {
    try {
      const actual = await readFile(filePath, 'utf8');
      if (actual.replace(/\r\n/g, '\n') !== expected.replace(/\r\n/g, '\n')) mismatches.push(path.relative('.', filePath));
    } catch {
      mismatches.push(path.relative('.', filePath));
    }
  }
  if (mismatches.length) {
    console.error(`Benchmark çıktıları güncel değil: ${mismatches.join(', ')}`);
    process.exitCode = 1;
  } else {
    console.log(`Planner benchmark doğrulandı: ${report.passedCount}/${report.scenarioCount} geçti.`);
  }
} else {
  for (const [filePath, content] of outputs) await writeFile(filePath, content, 'utf8');
  console.log(`Planner benchmark yazıldı: ${report.passedCount}/${report.scenarioCount} geçti.`);
}

if (report.passRate < 0.9) {
  console.error(`Planner benchmark başarı oranı %${Math.round(report.passRate * 100)}; gerekli eşik %90.`);
  process.exitCode = 1;
}
