import { readFile, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import path from 'node:path';
import process from 'node:process';
import {
  buildComparisonReport,
  type AnonymousUserSession,
  type BlindComparisonSubmission,
  type BlindMethodMapping,
  type ComparisonStudyPolicy,
  type HumanEvaluation
} from '../src/v4/benchmarks/comparison-benchmark.js';

interface StudyScenario {
  id: string;
  domain: string;
  idea: string;
}

interface StudyDefinition {
  schemaVersion: 2;
  studyId: string;
  policy: ComparisonStudyPolicy;
  scenarios: StudyScenario[];
  evaluationCriteria: string[];
  masterPromptSha256: string;
  frozenAt: string;
  frozenDigest: string;
  [key: string]: unknown;
}

const sha256 = (text: string) => createHash('sha256').update(text, 'utf8').digest('hex');

const root = path.resolve('benchmarks', 'comparison');
const checkOnly = process.argv.includes('--check');
const publishGate = process.argv.includes('--publish-gate');
const readJson = async <T>(name: string): Promise<T> =>
  JSON.parse(await readFile(path.join(root, name), 'utf8')) as T;
const study = await readJson<StudyDefinition>('study.json');

/**
 * Çalışma dondurulmuştur: senaryolar, ölçütler, eşikler ve master prompt veri
 * toplanmaya başladıktan sonra değiştirilemez. Sonuç kötü çıkınca ölçüt
 * değiştirme ihtimalini ortadan kaldırmak bu kontrolün tek amacı.
 *
 * `frozenDigest`, kendisi hariç tüm study.json'ın özetidir. Dolayısıyla
 * senaryo metnini, bir eşiği ya da ölçüt listesini değiştirmek özeti bozar ve
 * bu betik düşer. Meşru bir değişiklik gerekiyorsa yeni bir studyId açılır;
 * yürüyen çalışmanın tanımı düzenlenmez.
 */
function assertStudyFrozen(definition: StudyDefinition, masterPrompt: string): void {
  const { frozenDigest, ...withoutDigest } = definition;
  const expected = sha256(JSON.stringify(withoutDigest));
  if (frozenDigest !== expected) {
    throw new Error(
      'Çalışma tanımı dondurulduktan sonra değişmiş: study.json özeti uyuşmuyor. ' +
      'Yürüyen çalışmanın tanımı düzenlenmez; değişiklik gerekiyorsa yeni bir studyId açın.'
    );
  }
  const promptDigest = sha256(masterPrompt.replace(/\r\n/g, '\n'));
  if (definition.masterPromptSha256 !== promptDigest) {
    throw new Error(
      'master-prompt.md dondurulduktan sonra değişmiş. Master prompt çalışma boyunca sabittir.'
    );
  }
}

const masterPrompt = await readFile(path.join(root, 'master-prompt.md'), 'utf8');
assertStudyFrozen(study, masterPrompt);
const submissions = await readJson<BlindComparisonSubmission[]>('submissions.json');
const mapping = await readJson<BlindMethodMapping[]>('blind-map.json');
const humanEvaluations = await readJson<HumanEvaluation[]>('human-evaluations.json');
const userSessions = await readJson<AnonymousUserSession[]>('user-sessions.json');
const reportPath = path.join(root, 'latest-report.json');
const markdownPath = path.resolve('docs', 'product', 'COMPARISON_REPORT.md');
const modulePath = path.resolve('src', 'v4', 'product', 'generated-comparison-evidence.ts');

let generatedAt = new Date().toISOString();
if (checkOnly || publishGate) {
  try {
    generatedAt = (await readJson<{ generatedAt: string }>('latest-report.json')).generatedAt;
  } catch {
    generatedAt = 'missing-report';
  }
}

const report = buildComparisonReport({
  studyId: study.studyId,
  submissions,
  mapping,
  humanEvaluations,
  userSessions,
  policy: study.policy,
  generatedAt
});
const userParticipantsByCapability = Object.fromEntries(
  [...new Set(userSessions.map(session => session.capabilityId))]
    .map(capabilityId => [
      capabilityId,
      new Set(userSessions.filter(session => session.capabilityId === capabilityId).map(session => session.anonymousSessionId)).size
    ])
);
const json = `${JSON.stringify(report, null, 2)}\n`;
const moduleSource = `// Generated by \`npm run comparison:benchmark\`; do not edit manually.
export const COMPARISON_EVIDENCE: {
  studyId: string;
  reportPath: string;
  generatedAt: string;
  publicationEligible: boolean;
  userParticipantsByCapability: Record<string, number>;
} = Object.freeze(${JSON.stringify({
  studyId: report.studyId,
  reportPath: 'benchmarks/comparison/latest-report.json',
  generatedAt: report.generatedAt,
  publicationEligible: report.publicationGate.eligible,
  userParticipantsByCapability
}, null, 2)});
`;
const methodRows = (['baseline-chat', 'master-prompt', 'promtgen'] as const).map(method => {
  const result = report.byMethod[method];
  return `| ${method} | ${result?.samples || 0} | ${result?.averageScore ?? '—'} | ${result ? `${Math.round(result.averageScopeContainment * 100)}%` : '—'} | ${result ? `${Math.round(result.averageAcceptanceCoverage * 100)}%` : '—'} |`;
}).join('\n');
const markdown = `# PromtGen Karşılaştırmalı Sonuç Raporu

Bu rapor kör değerlendirme tamamlandıktan sonra standart AI sohbeti, master prompt ve PromtGen yöntemlerini karşılaştırır.

- Çalışma: \`${report.studyId}\`
- Son çalışma: ${report.generatedAt}
- Yayın kapısı: **${report.publicationGate.eligible ? 'Geçti' : 'Bloklu'}**
- Anonim kullanıcı katılımcısı: ${report.userEvidence.validParticipants}
- Gerçek karşılaştırma submission sayısı: ${report.blindedEvaluation.length}

| Yöntem | Örnek | Ortalama skor | Kapsam koruması | Kabul kriteri kapsamı |
|---|---:|---:|---:|---:|
${methodRows}

## Kullanıcı sonucu

- Tamamlama: ${Math.round(report.userEvidence.completionRate * 100)}%
- İlk export: ${Math.round(report.userEvidence.firstExportRate * 100)}%
- Küçük düzenlemeyle MVP kabulü: ${Math.round(report.userEvidence.minorEditMvpAcceptanceRate * 100)}%
- Ortalama memnuniyet: ${report.userEvidence.averageSatisfaction || '—'}/5

## Açık yayın engelleri

${report.publicationGate.blockers.map(blocker => `- ${blocker}`).join('\n') || '- Açık engel yok.'}

Bu rapor boş veya yetersiz örneklerle ürün üstünlüğü iddia etmez. Yöntem bilgisi değerlendirmeden önce submission içine eklenemez.
`;
const outputs = [[reportPath, json], [markdownPath, markdown], [modulePath, moduleSource]] as const;

if (checkOnly) {
  const mismatches: string[] = [];
  for (const [filePath, expected] of outputs) {
    try {
      const actual = await readFile(filePath, 'utf8');
      if (actual.replace(/\r\n/g, '\n') !== expected.replace(/\r\n/g, '\n')) mismatches.push(path.relative('.', filePath));
    } catch {
      mismatches.push(path.relative('.', filePath));
    }
  }
  if (mismatches.length) {
    console.error(`Karşılaştırma çıktıları güncel değil: ${mismatches.join(', ')}`);
    process.exitCode = 1;
  } else {
    console.log(`Karşılaştırma evidence doğrulandı; yayın kapısı ${report.publicationGate.eligible ? 'açık' : 'bloklu'}.`);
  }
} else if (!publishGate) {
  for (const [filePath, content] of outputs) await writeFile(filePath, content, 'utf8');
  console.log(`Karşılaştırma raporu yazıldı; ${report.blindedEvaluation.length} kör submission değerlendirildi.`);
}

if (publishGate && !report.publicationGate.eligible) {
  console.error(`Karşılaştırma yayın kapısı bloklu:\n- ${report.publicationGate.blockers.join('\n- ')}`);
  process.exitCode = 1;
}
